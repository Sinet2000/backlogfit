/** Thrown inside a handler to reject the event: the draft is discarded and the input state returned. */
class Rejection extends Error {
  readonly code: ErrorCode | null;
  readonly closeWith: CloseReason | null;
  constructor(code: ErrorCode | null, closeWith: CloseReason | null = null) {
    super(code ?? closeWith ?? 'rejected');
    this.code = code;
    this.closeWith = closeWith;
  }
}

function fail(code: ErrorCode | null, closeWith: CloseReason | null = null): never {
  throw new Rejection(code, closeWith);
}

interface Tx {
  d: RoomState;
  ctx: Ctx;
  fx: Effect[];
  welcomes: { conn: string; pid: string; resumeToken: string | null }[];
  mutated: boolean;
  broadcast: boolean;
}

const DEFAULT_TIMER_SECONDS = 60;
const INVALID_LINE_REFS_MAX = 20;

function changed(tx: Tx): void {
  tx.mutated = true;
  tx.broadcast = true;
}

function send(tx: Tx, to: string, msg: Extract<Effect, { type: 'send' }>['msg']): void {
  tx.fx.push({ type: 'send', to, msg });
}

// ---------------------------------------------------------------------------------------------
// Room creation

/**
 * Build the initial state for a validated POST /api/rooms body. `roomId` is generated by the
 * adapter (128-bit, base64url). Lifetime is clamped to limits.maxLifetimeMs.
 */
export function createRoom(
  req: CreateRoomRequest,
  roomId: string,
  ctx: Ctx,
  limits: Limits = DEFAULT_LIMITS,
): ReduceResult {
  const now = ctx.now;
  const lifetime = Math.min(req.lifetimeHours * HOUR_MS, limits.maxLifetimeMs);
  const c = req.config;
  const state: RoomState = {
    v: 1,
    roomId,
    createdAt: now,
    expiresAt: now + lifetime,
    lastActivityAt: now,
    rev: 0,
    config: {
      scale: c.scale.map((card) => ({ ...card })),
      taskPolicy: c.taskPolicy,
      allowlist: [...c.allowlist],
      idPattern: c.idPattern,
      linkTemplate: c.linkTemplate,
      maxParticipants: Math.min(c.maxParticipants, limits.maxParticipants),
      theme: c.theme,
    },
    settings: {
      autoReveal: c.autoReveal,
      anonymousAfterReveal: c.anonymousAfterReveal,
      allowSpectators: c.allowSpectators,
      lobby: c.lobby,
      timerSeconds: c.timerSeconds,
      locked: false,
    },
    secrets: { joinHash: req.joinHash, adminHash: req.adminHash, passcode: req.passcode ?? null },
    passcodeFailures: 0,
    passcodeLocked: false,
    limits: { ...limits },
    participants: [],
    tasks: [],
    currentTaskId: null,
    timer: null,
    alarmAt: null,
    closed: null,
  };
  state.alarmAt = nextDeadline(state);
  return { state, effects: [{ type: 'scheduleAlarm', at: state.alarmAt }] };
}

// ---------------------------------------------------------------------------------------------
// Reducer

/**
 * Pure transition function. Never mutates `state`; returns the same object when nothing changed
 * (including every rejected event). Time and ids come only from `ctx`.
 */
export function reduce(state: RoomState, event: RoomEvent, ctx: Ctx): ReduceResult {
  if (state.closed !== null) {
    const conn = 'conn' in event && event.type !== 'disconnect' ? event.conn : null;
    return {
      state,
      effects: conn ? [{ type: 'close', to: conn, reason: state.closed }] : [],
    };
  }

  const tx: Tx = {
    d: structuredClone(state),
    ctx,
    fx: [],
    welcomes: [],
    mutated: false,
    broadcast: false,
  };

  try {
    if (ctx.now >= state.expiresAt) closeRoom(tx, 'expired');
    else if (ctx.now >= idleAt(state)) closeRoom(tx, 'idle');
    else {
      handle(tx, event);
      settle(tx);
    }
  } catch (e) {
    if (!(e instanceof Rejection)) throw e;
    const effects: Effect[] = [];
    if (event.type === 'message') {
      if (e.code) {
        effects.push({
          type: 'send',
          to: event.conn,
          msg: { type: 'error', code: e.code, ref: event.msg.type },
        });
      }
      if (e.closeWith) effects.push({ type: 'close', to: event.conn, reason: e.closeWith });
    }
    return { state, effects };
  }

  return finish(state, tx);
}

function finish(original: RoomState, tx: Tx): ReduceResult {
  const { d } = tx;
  for (const w of tx.welcomes) {
    const p = d.participants.find((x) => x.id === w.pid);
    if (!p || p.conn !== w.conn || p.status !== 'active') continue;
    send(tx, w.conn, {
      type: 'welcome',
      v: 1,
      you: {
        participantId: p.id,
        role: p.role,
        authority: p.authority,
        isAdmin: p.authority === 'admin',
        ...(w.resumeToken ? { resumeToken: w.resumeToken } : {}),
      },
      room: project(d, p.id),
      serverTime: tx.ctx.now,
    });
  }
  if (tx.broadcast && d.closed === null) {
    d.rev += 1;
    tx.fx.push({ type: 'broadcastState' });
  }
  const next = d.closed === null ? nextDeadline(d) : null;
  const a = d.alarmAt;
  // An alarm that fires early is harmless (tick reschedules), so only move it earlier.
  const reschedule = next === null ? a !== null : a === null || next < a || a <= tx.ctx.now;
  if (reschedule) {
    d.alarmAt = next;
    tx.mutated = true;
    tx.fx.push({ type: 'scheduleAlarm', at: next });
  }
  return { state: tx.mutated ? d : original, effects: tx.fx };
}

export function nextDeadline(state: RoomState): number {
  let at = Math.min(state.expiresAt, idleAt(state));
  if (state.timer) at = Math.min(at, state.timer.endsAt);
  return at;
}

function handle(tx: Tx, event: RoomEvent): void {
  switch (event.type) {
    case 'connect':
    case 'tick':
      return;
    case 'disconnect':
      disconnect(tx, event.conn);
      return;
    case 'message':
      message(tx, event.conn, event.msg, event.auth);
      return;
  }
}

/** Post-event rules: timer expiry and auto-reveal. */
function settle(tx: Tx): void {
  const { d } = tx;
  if (d.timer && tx.ctx.now >= d.timer.endsAt) {
    d.timer = null;
    if (phaseOf(d) === 'voting') reveal(tx);
    changed(tx);
  }
  if (d.settings.autoReveal && phaseOf(d) === 'voting') {
    const round = currentRound(d);
    const voters = d.participants.filter(
      (p) => p.status === 'active' && p.role === 'voter' && p.conn !== null,
    );
    if (
      round &&
      voters.length > 0 &&
      voters.every((p) => round.votes.some((vote) => vote.pid === p.id))
    ) {
      reveal(tx);
    }
  }
}

function closeRoom(tx: Tx, reason: CloseReason): void {
  const { d } = tx;
  for (const p of d.participants) {
    if (p.conn !== null) tx.fx.push({ type: 'close', to: p.conn, reason });
  }
  d.closed = reason;
  d.timer = null;
  tx.mutated = true;
  tx.fx.push({ type: 'deleteAll', reason });
}

function disconnect(tx: Tx, conn: string): void {
  const { d } = tx;
  const p = byConn(d, conn);
  if (!p) return;
  if (p.status === 'lobby') d.participants = d.participants.filter((x) => x !== p);
  else p.conn = null;
  changed(tx);
}

function byConn(d: RoomState, conn: string): Participant | undefined {
  return d.participants.find((p) => p.conn === conn);
}

function byId(d: RoomState, id: string): Participant | undefined {
  return d.participants.find((p) => p.id === id);
}

function taskById(d: RoomState, id: string): Task {
  return d.tasks.find((t) => t.id === id) ?? fail('unknown_task');
}

function message(tx: Tx, conn: string, msg: ClientMessage, auth: HelloAuth | undefined): void {
  if (msg.type === 'hello') {
    hello(tx, conn, msg, auth);
    return;
  }
  const p = byConn(tx.d, conn) ?? fail('not_joined');
  if (p.status === 'lobby') fail('lobby_waiting');
  if (msg.type === 'ping') {
    send(tx, conn, { type: 'pong', serverTime: tx.ctx.now });
    return;
  }
  if (msg.type === 'vote' || msg.type === 'unvote') vote(tx, p, msg);
  else admin(tx, p, conn, msg);
  tx.d.lastActivityAt = tx.ctx.now;
  tx.mutated = true;
}

// ---------------------------------------------------------------------------------------------
// Joining

function hello(tx: Tx, conn: string, msg: HelloMessage, auth: HelloAuth | undefined): void {
  const { d } = tx;
  // Adapters must run verifyHello() first; a hello without auth is treated as unauthenticated.
  if (!auth) fail('unauthorized', 'rejected');
  if (byConn(d, conn)) fail('already_joined');
  // Same answer as an unknown room: no oracle for whether the room exists.
  if (!auth.joinOk) fail(null, 'not_found');
  if (msg.adminSecret !== undefined && !auth.adminOk) fail('unauthorized', 'rejected');

  const resumed = auth.resumeParticipantId ? byId(d, auth.resumeParticipantId) : undefined;
  if (resumed) {
    if (resumed.conn !== null && resumed.conn !== conn) {
      tx.fx.push({ type: 'close', to: resumed.conn, reason: 'replaced' });
    }
    resumed.conn = conn;
    resumed.resumeHash = auth.resume.hash;
    if (auth.adminOk) {
      resumed.authority = 'admin';
      resumed.status = 'active';
    }
    admit(tx, resumed, auth.resume.token);
    return;
  }

  const isAdmin = auth.adminOk;
  if (!isAdmin) {
    if (d.settings.locked) fail('room_locked', 'rejected');
    if (msg.role === 'spectator' && !d.settings.allowSpectators) {
      fail('spectators_disabled', 'rejected');
    }
    if (d.secrets.passcode) {
      if (d.passcodeLocked) fail('passcode_locked', 'rejected');
      if (auth.passcodeOk !== true) {
        // Not a Rejection: the failure counter must persist.
        d.passcodeFailures += 1;
        if (d.passcodeFailures >= d.limits.passcodeMaxAttempts) d.passcodeLocked = true;
        changed(tx);
        send(tx, conn, { type: 'error', code: 'bad_passcode', ref: 'hello' });
        tx.fx.push({ type: 'close', to: conn, reason: 'rejected' });
        return;
      }
    }
    const connected = d.participants.filter((p) => p.conn !== null).length;
    if (connected >= d.config.maxParticipants) fail('room_full', 'rejected');
  }
  pruneRecords(d);

  const p: Participant = {
    id: tx.ctx.randomId(),
    name: msg.name,
    role: msg.role,
    authority: isAdmin ? 'admin' : 'none',
    status: !isAdmin && d.settings.lobby ? 'lobby' : 'active',
    conn,
    resumeHash: auth.resume.hash,
    joinedAt: tx.ctx.now,
  };
  d.participants.push(p);
  admit(tx, p, auth.resume.token);
}

function admit(tx: Tx, p: Participant, resumeToken: string): void {
  if (p.status === 'lobby' && p.conn !== null) {
    send(tx, p.conn, { type: 'lobby', status: 'waiting', resumeToken });
  } else if (p.conn !== null) {
    tx.welcomes.push({ conn: p.conn, pid: p.id, resumeToken });
    tx.d.lastActivityAt = tx.ctx.now;
  }
  changed(tx);
}

/**
 * Disconnected records are kept for resume, but bounded: past 2× maxParticipants the oldest
 * disconnected regular participants are forgotten (their revealed votes keep a name snapshot).
 */
function pruneRecords(d: RoomState): void {
  const cap = d.config.maxParticipants * 2;
  while (d.participants.length >= cap) {
    const victim = d.participants.find((p) => p.conn === null && p.authority === 'none');
    if (!victim) fail('room_full', 'rejected');
    removeParticipant(d, victim);
  }
}

function removeParticipant(d: RoomState, p: Participant): void {
  d.participants = d.participants.filter((x) => x.id !== p.id);
  for (const task of d.tasks) {
    for (const round of task.rounds) {
      if (round.revealedAt === null) round.votes = round.votes.filter((v) => v.pid !== p.id);
    }
  }
}

// ---------------------------------------------------------------------------------------------
// Voting

function vote(tx: Tx, p: Participant, msg: Extract<ClientMessage, { type: 'vote' | 'unvote' }>) {
  const { d } = tx;
  if (p.role !== 'voter') fail('forbidden');
  const task = currentTask(d);
  const round = currentRound(d);
  if (!task || !round || round.revealedAt !== null) return fail('not_voting');
  if (msg.taskId !== task.id) fail('wrong_task');
  if (msg.round !== round.n) fail('wrong_round');
  const others = round.votes.filter((v) => v.pid !== p.id);
  if (msg.type === 'vote') {
    if (!d.config.scale.some((c) => c.value === msg.value)) fail('invalid_value');
    round.votes = [...others, { pid: p.id, name: p.name, value: msg.value }];
  } else {
    round.votes = others;
  }
  changed(tx);
}

function newRound(d: RoomState, n: number, now: number): Round {
  return {
    n,
    votes: [],
    startedAt: now,
    revealedAt: null,
    anonymous: d.settings.anonymousAfterReveal,
  };
}

function reveal(tx: Tx): void {
  const round = currentRound(tx.d);
  if (round && round.revealedAt === null) round.revealedAt = tx.ctx.now;
  tx.d.timer = null;
  changed(tx);
}

function selectTask(tx: Tx, task: Task): void {
  tx.d.currentTaskId = task.id;
  if (task.rounds.length === 0) task.rounds.push(newRound(tx.d, 1, tx.ctx.now));
  tx.d.timer = null;
}


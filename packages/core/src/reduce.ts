// Admin

const ADMIN_ONLY = new Set<AdminMessage['type']>([
  'admin.settings',
  'admin.promote',
  'admin.demote',
  'admin.extend',
  'admin.close',
]);

function admin(tx: Tx, p: Participant, conn: string, msg: AdminMessage) {
  if (!isFacilitator(p)) fail('forbidden');
  if (ADMIN_ONLY.has(msg.type) && p.authority !== 'admin') fail('forbidden');
  const { d } = tx;
  const now = tx.ctx.now;

  switch (msg.type) {
    case 'admin.tasks.add': {
      const opts = {
        policy: d.config.taskPolicy,
        allowlist: d.config.allowlist,
        idPattern: d.config.idPattern,
        linkTemplate: d.config.linkTemplate,
      };
      const added: Task[] = [];
      const invalid: number[] = [];
      msg.lines.forEach((line, i) => {
        const r = parseTaskLine(line, opts);
        if (r.ok) added.push({ id: '', ...r.task, rounds: [], final: null });
        else if (r.error !== 'empty') invalid.push(i);
      });
      if (d.tasks.length + added.length > d.limits.maxTasks) fail('too_many_tasks');
      for (const t of added) t.id = tx.ctx.randomId();
      d.tasks.push(...added);
      if (invalid.length > 0) {
        send(tx, conn, {
          type: 'error',
          code: 'invalid_task',
          ref: `lines:${invalid.slice(0, INVALID_LINE_REFS_MAX).join(',')}`,
        });
      }
      if (added.length > 0) changed(tx);
      return;
    }
    case 'admin.tasks.remove': {
      const task = taskById(d, msg.taskId);
      d.tasks = d.tasks.filter((t) => t !== task);
      if (d.currentTaskId === task.id) {
        d.currentTaskId = null;
        d.timer = null;
      }
      return changed(tx);
    }
    case 'admin.tasks.move': {
      const task = taskById(d, msg.taskId);
      const rest = d.tasks.filter((t) => t !== task);
      rest.splice(Math.min(msg.toIndex, rest.length), 0, task);
      d.tasks = rest;
      return changed(tx);
    }
    case 'admin.select':
      selectTask(tx, taskById(d, msg.taskId));
      return changed(tx);
    case 'admin.next': {
      const start = d.tasks.findIndex((t) => t.id === d.currentTaskId);
      const ordered = [...d.tasks.slice(start + 1), ...d.tasks.slice(0, Math.max(start, 0))];
      const next = ordered.find((t) => t.final === null);
      if (next) selectTask(tx, next);
      else {
        d.currentTaskId = null;
        d.timer = null;
      }
      return changed(tx);
    }
    case 'admin.reveal':
      if (phaseOf(d) !== 'voting') fail('not_voting');
      return reveal(tx);
    case 'admin.revote': {
      const task = currentTask(d) ?? fail('no_current_task');
      const last = task.rounds[task.rounds.length - 1];
      if (last && last.revealedAt === null) {
        last.votes = [];
        last.startedAt = now;
      } else {
        task.rounds.push(newRound(d, (last?.n ?? 0) + 1, now));
      }
      d.timer = null;
      return changed(tx);
    }
    case 'admin.final':
      taskById(d, msg.taskId).final = msg.value;
      return changed(tx);
    case 'admin.timer':
      if (msg.action === 'stop') d.timer = null;
      else {
        const seconds = msg.seconds ?? d.settings.timerSeconds ?? DEFAULT_TIMER_SECONDS;
        d.timer = { endsAt: now + seconds * 1000, seconds };
      }
      return changed(tx);
    case 'admin.settings': {
      const s = d.settings;
      if (msg.autoReveal !== undefined) s.autoReveal = msg.autoReveal;
      if (msg.allowSpectators !== undefined) s.allowSpectators = msg.allowSpectators;
      if (msg.timerSeconds !== undefined) s.timerSeconds = msg.timerSeconds;
      if (msg.anonymousAfterReveal !== undefined) {
        s.anonymousAfterReveal = msg.anonymousAfterReveal;
        const round = currentRound(d);
        if (msg.anonymousAfterReveal && round && round.revealedAt === null) round.anonymous = true;
      }
      if (msg.lobby !== undefined) {
        s.lobby = msg.lobby;
        if (!msg.lobby) {
          for (const w of d.participants.filter((x) => x.status === 'lobby')) approve(tx, w);
        }
      }
      return changed(tx);
    }
    case 'admin.lock':
      d.settings.locked = msg.locked;
      if (!msg.locked) {
        d.passcodeFailures = 0;
        d.passcodeLocked = false;
      }
      return changed(tx);
    case 'admin.kick': {
      const target = byId(d, msg.participantId) ?? fail('unknown_participant');
      if (target.id === p.id || target.authority === 'admin') fail('invalid_target');
      if (target.authority === 'coadmin' && p.authority !== 'admin') fail('forbidden');
      removeParticipant(d, target);
      if (target.conn !== null) tx.fx.push({ type: 'close', to: target.conn, reason: 'kicked' });
      return changed(tx);
    }
    case 'admin.promote':
    case 'admin.demote': {
      const target = byId(d, msg.participantId) ?? fail('unknown_participant');
      const from = msg.type === 'admin.promote' ? 'none' : 'coadmin';
      if (target.status !== 'active' || target.authority !== from) fail('invalid_target');
      target.authority = msg.type === 'admin.promote' ? 'coadmin' : 'none';
      return changed(tx);
    }
    case 'admin.lobby': {
      const target = byId(d, msg.participantId);
      if (target?.status !== 'lobby') return fail('unknown_participant');
      if (msg.decision === 'approve') approve(tx, target);
      else {
        removeParticipant(d, target);
        if (target.conn !== null) {
          send(tx, target.conn, { type: 'lobby', status: 'denied' });
          tx.fx.push({ type: 'close', to: target.conn, reason: 'denied' });
        }
      }
      return changed(tx);
    }
    case 'admin.extend':
      d.expiresAt = Math.min(d.expiresAt + msg.hours * HOUR_MS, maxExpiresAt(d));
      return changed(tx);
    case 'admin.close':
      return closeRoom(tx, 'closed');
  }
}

function approve(tx: Tx, p: Participant): void {
  p.status = 'active';
  // The resume token was delivered with lobby{waiting}; the welcome does not repeat it.
  if (p.conn !== null) tx.welcomes.push({ conn: p.conn, pid: p.id, resumeToken: null });
  changed(tx);
}

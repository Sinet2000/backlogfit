// Parsing entry points

export type ParseResult<T> = { ok: true; msg: T } | { ok: false; code: ErrorCode };

const decoder = new TextDecoder('utf-8', { fatal: true });
const encoder = new TextEncoder();

function exceedsBytes(s: string, maxBytes: number): boolean {
  if (s.length > maxBytes) return true;
  // A UTF-16 unit encodes to at most 3 UTF-8 bytes, so short strings skip the encode.
  return s.length * 3 > maxBytes && encoder.encode(s).byteLength > maxBytes;
}

/**
 * Size cap → JSON.parse → strict schema. Never throws. Accepts text frames or binary frames
 * (decoded as strict UTF-8).
 */
export function parseClientMessage(
  raw: string | Uint8Array | ArrayBuffer,
  maxBytes: number = DEFAULT_MAX_MESSAGE_BYTES,
): ParseResult<ClientMessage> {
  let textFrame: string;
  if (typeof raw === 'string') {
    if (exceedsBytes(raw, maxBytes)) return { ok: false, code: 'too_large' };
    textFrame = raw;
  } else {
    const bytes = raw instanceof Uint8Array ? raw : new Uint8Array(raw);
    if (bytes.byteLength > maxBytes) return { ok: false, code: 'too_large' };
    try {
      textFrame = decoder.decode(bytes);
    } catch {
      return { ok: false, code: 'bad_json' };
    }
  }
  let data: unknown;
  try {
    data = JSON.parse(textFrame);
  } catch {
    return { ok: false, code: 'bad_json' };
  }
  if (
    typeof data === 'object' &&
    data !== null &&
    !Array.isArray(data) &&
    (data as Record<string, unknown>).type === 'hello' &&
    (data as Record<string, unknown>).v !== PROTOCOL_VERSION
  ) {
    return { ok: false, code: 'unsupported_version' };
  }
  const result = v.safeParse(ClientMessageSchema, data);
  return result.success ? { ok: true, msg: result.output } : { ok: false, code: 'invalid_message' };
}

export function parseServerMessage(raw: string): ParseResult<ServerMessage> {
  let data: unknown;
  try {
    data = JSON.parse(raw);
  } catch {
    return { ok: false, code: 'bad_json' };
  }
  const result = v.safeParse(ServerMessageSchema, data);
  return result.success ? { ok: true, msg: result.output } : { ok: false, code: 'invalid_message' };
}


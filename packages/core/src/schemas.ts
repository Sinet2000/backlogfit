import * as v from 'valibot';
import {
  CARD_LABEL_MAX,
  CARD_VALUE_MAX,
  SCALE_MAX_CARDS,
  SCALE_MIN_CARDS,
  validateScale,
} from './scales.ts';
import {
  ALLOWLIST_MAX,
  ID_PATTERN_MAX,
  isSafeIdPattern,
  normalizeAllowlistEntry,
  TASK_LINE_MAX,
  URL_MAX,
  validateLinkTemplate,
} from './tasks.ts';
import { hasUnsafeChars } from './text.ts';

export const PROTOCOL_VERSION = 1;
export const DEFAULT_MAX_MESSAGE_BYTES = 16 * 1024;

export const NAME_MAX = 40;
export const FINAL_MAX = 16;
export const PASSCODE_MAX = 64;
export const LINES_PER_ADD_MAX = 200;
export const TIMER_MIN_SECONDS = 5;
export const TIMER_MAX_SECONDS = 3600;
export const ROUND_MAX = 1000;
export const PARTICIPANTS_HARD_MAX = 500;

// ---------------------------------------------------------------------------------------------
// Primitives

/** User-visible text: NFC, trimmed, length-capped, no control/bidi/zero-width characters. */
const text = (min: number, max: number) =>
  v.pipe(
    v.string(),
    v.maxLength(max * 4),
    v.normalize('NFC'),
    v.trim(),
    v.minLength(min),
    v.maxLength(max),
    v.check((s) => !hasUnsafeChars(s), 'unsafe characters'),
  );

/** Opaque identifiers generated by the server (participant, task, room, connection). */
export const IdSchema = v.pipe(
  v.string(),
  v.minLength(1),
  v.maxLength(64),
  v.regex(/^[A-Za-z0-9_-]+$/),
);

/** 128-bit+ secrets encoded as base64url. */
export const SecretSchema = v.pipe(
  v.string(),
  v.minLength(16),
  v.maxLength(128),
  v.regex(/^[A-Za-z0-9_-]+$/),
);

/** Lower-case hex SHA-256 digest. */
export const HashSchema = v.pipe(v.string(), v.length(64), v.regex(/^[0-9a-f]{64}$/));

const SaltSchema = v.pipe(v.string(), v.minLength(16), v.maxLength(64), v.regex(/^[0-9a-f]+$/));

const int = (min: number, max: number) =>
  v.pipe(v.number(), v.integer(), v.minValue(min), v.maxValue(max));

export const DisplayNameSchema = text(1, NAME_MAX);
export const CardValueSchema = text(1, CARD_VALUE_MAX);
export const FinalValueSchema = text(1, FINAL_MAX);
export const RoleSchema = v.picklist(['voter', 'spectator']);
export const AuthoritySchema = v.picklist(['admin', 'coadmin', 'none']);
export const TaskPolicySchema = v.picklist(['ids', 'links', 'allowlist']);
export const ThemeSchema = v.picklist(['corporate', 'colorful']);
export const TimerSecondsSchema = int(TIMER_MIN_SECONDS, TIMER_MAX_SECONDS);

// ---------------------------------------------------------------------------------------------
// Domain

export const CardSchema = v.strictObject({
  value: CardValueSchema,
  label: text(1, CARD_LABEL_MAX),
  numeric: v.exactOptional(v.pipe(v.number(), v.finite(), v.minValue(-1e6), v.maxValue(1e6))),
  kind: v.picklist(['number', 'tshirt', 'special']),
  color: v.pipe(v.string(), v.regex(/^#[0-9a-fA-F]{6}$/)),
});

export const ScaleSchema = v.pipe(
  v.array(CardSchema),
  v.minLength(SCALE_MIN_CARDS),
  v.maxLength(SCALE_MAX_CARDS),
  v.check((cards) => validateScale(cards) === null, 'invalid scale'),
);

const AllowlistSchema = v.pipe(
  v.array(v.pipe(v.string(), v.maxLength(253))),
  v.maxLength(ALLOWLIST_MAX),
  v.check((xs) => xs.every((x) => normalizeAllowlistEntry(x) !== null), 'invalid allowlist entry'),
  v.transform((xs) => [...new Set(xs.map((x) => normalizeAllowlistEntry(x) ?? ''))]),
);

export const RoomConfigSchema = v.pipe(
  v.strictObject({
    scale: ScaleSchema,
    taskPolicy: v.optional(TaskPolicySchema, 'ids'),
    allowlist: v.optional(AllowlistSchema, []),
    idPattern: v.optional(
      v.nullable(
        v.pipe(
          v.string(),
          v.maxLength(ID_PATTERN_MAX),
          v.check((p) => isSafeIdPattern(p), 'unsafe id pattern'),
        ),
      ),
      null,
    ),
    linkTemplate: v.optional(v.nullable(v.pipe(v.string(), v.maxLength(URL_MAX))), null),
    autoReveal: v.optional(v.boolean(), true),
    anonymousAfterReveal: v.optional(v.boolean(), false),
    allowSpectators: v.optional(v.boolean(), true),
    lobby: v.optional(v.boolean(), false),
    timerSeconds: v.optional(v.nullable(TimerSecondsSchema), null),
    maxParticipants: v.optional(int(2, PARTICIPANTS_HARD_MAX), 50),
    theme: v.optional(ThemeSchema, 'corporate'),
  }),
  v.check(
    (c) =>
      c.linkTemplate === null || validateLinkTemplate(c.linkTemplate, c.taskPolicy, c.allowlist),
    'invalid link template',
  ),
  v.check((c) => c.taskPolicy !== 'allowlist' || c.allowlist.length > 0, 'empty allowlist'),
);

export type RoomConfig = v.InferOutput<typeof RoomConfigSchema>;
export type RoomConfigInput = v.InferInput<typeof RoomConfigSchema>;

export const PasscodeHashSchema = v.strictObject({ salt: SaltSchema, hash: HashSchema });
export type PasscodeHash = v.InferOutput<typeof PasscodeHashSchema>;

/** Body of POST /api/rooms. The browser generates the secrets and sends only their hashes. */
export const CreateRoomRequestSchema = v.strictObject({
  v: v.literal(PROTOCOL_VERSION),
  config: RoomConfigSchema,
  joinHash: HashSchema,
  adminHash: HashSchema,
  lifetimeHours: int(1, 24),
  passcode: v.optional(PasscodeHashSchema),
});
export type CreateRoomRequest = v.InferOutput<typeof CreateRoomRequestSchema>;

// ---------------------------------------------------------------------------------------------
// Client → server

const msg = <T extends string, E extends v.ObjectEntries>(type: T, entries: E) =>
  v.strictObject({ type: v.literal(type), ...entries });

const taskId = { taskId: IdSchema };
const participantId = { participantId: IdSchema };

export const HelloSchema = msg('hello', {
  v: v.literal(PROTOCOL_VERSION),
  joinSecret: SecretSchema,
  name: DisplayNameSchema,
  role: RoleSchema,
  passcode: v.optional(v.pipe(v.string(), v.minLength(1), v.maxLength(PASSCODE_MAX))),
  adminSecret: v.optional(SecretSchema),
  resumeToken: v.optional(SecretSchema),
});

export const ClientMessageSchema = v.variant('type', [
  HelloSchema,
  msg('vote', { ...taskId, round: int(1, ROUND_MAX), value: CardValueSchema }),
  msg('unvote', { ...taskId, round: int(1, ROUND_MAX) }),
  msg('ping', {}),
  msg('admin.tasks.add', {
    lines: v.pipe(
      v.array(v.pipe(v.string(), v.maxLength(TASK_LINE_MAX))),
      v.minLength(1),
      v.maxLength(LINES_PER_ADD_MAX),
    ),
  }),
  msg('admin.tasks.remove', taskId),
  msg('admin.tasks.move', { ...taskId, toIndex: int(0, 100_000) }),
  msg('admin.next', {}),
  msg('admin.select', taskId),
  msg('admin.reveal', {}),
  msg('admin.revote', {}),
  msg('admin.final', { ...taskId, value: v.nullable(FinalValueSchema) }),
  msg('admin.timer', {
    action: v.picklist(['start', 'stop']),
    seconds: v.optional(TimerSecondsSchema),
  }),
  msg('admin.settings', {
    autoReveal: v.optional(v.boolean()),
    anonymousAfterReveal: v.optional(v.boolean()),
    allowSpectators: v.optional(v.boolean()),
    lobby: v.optional(v.boolean()),
    timerSeconds: v.optional(v.nullable(TimerSecondsSchema)),
  }),
  msg('admin.lock', { locked: v.boolean() }),
  msg('admin.kick', participantId),
  msg('admin.promote', participantId),
  msg('admin.demote', participantId),
  msg('admin.lobby', { ...participantId, decision: v.picklist(['approve', 'deny']) }),
  msg('admin.extend', { hours: int(1, 24) }),
  msg('admin.close', {}),
]);

export type ClientMessage = v.InferOutput<typeof ClientMessageSchema>;
export type ClientMessageInput = v.InferInput<typeof ClientMessageSchema>;
